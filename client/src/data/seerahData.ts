// Helper functions
export const getChaptersByCategory = (categoryId: string): SeerahChapter[] => {
  const category = seerahCategories.find((cat) => cat.id === categoryId);
  if (!category) return [];

  return seerahChapters
    .filter((chapter) => category.chapters.includes(chapter.id))
    .sort((a, b) => a.order - b.order);
};

export const getChapterById = (id: string): SeerahChapter | undefined => {
  return seerahChapters.find((chapter) => chapter.id === id);
};

export const getRelatedChapters = (chapterId: string): SeerahChapter[] => {
  const chapter = getChapterById(chapterId);
  if (!chapter || !chapter.relatedChapters) return [];

  return chapter.relatedChapters
    .map((id) => getChapterById(id))
    .filter((ch): ch is SeerahChapter => ch !== undefined);
};

export const searchChapters = (query: string): SeerahChapter[] => {
  const lowercaseQuery = query.toLowerCase();
  return seerahChapters.filter(
    (chapter) =>
      chapter.title.toLowerCase().includes(lowercaseQuery) ||
      chapter.description.toLowerCase().includes(lowercaseQuery) ||
      chapter.details.toLowerCase().includes(lowercaseQuery) ||
      chapter.keywords.some((keyword) =>
        keyword.toLowerCase().includes(lowercaseQuery),
      ),
  );
};
